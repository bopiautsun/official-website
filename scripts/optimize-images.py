"""Generate responsive images and their browser manifest; preserve source files."""

import json
from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "asset"
OUTPUT = ASSETS / "optimized"
MANIFEST = ROOT / "image-manifest.js"
PREFIX = "window.NSP_IMAGE_VARIANTS = "


def main():
    # A fresh clone contains optimized images, not the large originals. Retain
    # existing entries when only a new source image is available locally.
    variants = {}
    if MANIFEST.exists():
        contents = MANIFEST.read_text(encoding="utf-8")
        variants = json.loads(contents.split(PREFIX, 1)[1].strip().removesuffix(";"))

    OUTPUT.mkdir(exist_ok=True)
    updated = 0
    for source in sorted(ASSETS.iterdir()):
        if source.suffix.lower() not in {".jpg", ".jpeg", ".png"}:
            continue
        with Image.open(source) as image:
            image = ImageOps.exif_transpose(image)
            if image.mode not in {"RGB", "RGBA"}:
                image = image.convert("RGB")
            entries = []
            for width in (640, 1600):
                resized = image.copy()
                resized.thumbnail((width, round(width * image.height / image.width)))
                target = OUTPUT / f"{source.stem}-{width}.webp"
                resized.save(target, "WEBP", quality=84, method=6)
                entries.append({
                    "src": target.relative_to(ROOT).as_posix(),
                    "width": resized.width,
                    "height": resized.height,
                })
            variants[source.relative_to(ROOT).as_posix()] = entries
            updated += 1

    contents = (
        "// Generated by scripts/optimize-images.py. Do not edit by hand.\n"
        + PREFIX
        + json.dumps(dict(sorted(variants.items())), ensure_ascii=False, indent=2)
        + ";\n"
    )
    MANIFEST.write_text(contents, encoding="utf-8", newline="\n")
    print(f"Updated {updated} source images. Manifest contains {len(variants)} images.")


if __name__ == "__main__":
    main()
